//! KeyboardEvent.code (physical key) to PC/AT set 1 scan code. Sending scan codes keeps the
//! remote keyboard layout in charge, so a Dutch or US layout on the remote machine just works.

/// Returns (scan code, extended key).
pub fn scancode(code: &str) -> Option<(u16, bool)> {
    let s = |c: u16| Some((c, false));
    let e = |c: u16| Some((c, true));
    match code {
        "Escape" => s(0x01),
        "Digit1" => s(0x02),
        "Digit2" => s(0x03),
        "Digit3" => s(0x04),
        "Digit4" => s(0x05),
        "Digit5" => s(0x06),
        "Digit6" => s(0x07),
        "Digit7" => s(0x08),
        "Digit8" => s(0x09),
        "Digit9" => s(0x0a),
        "Digit0" => s(0x0b),
        "Minus" => s(0x0c),
        "Equal" => s(0x0d),
        "Backspace" => s(0x0e),
        "Tab" => s(0x0f),
        "KeyQ" => s(0x10),
        "KeyW" => s(0x11),
        "KeyE" => s(0x12),
        "KeyR" => s(0x13),
        "KeyT" => s(0x14),
        "KeyY" => s(0x15),
        "KeyU" => s(0x16),
        "KeyI" => s(0x17),
        "KeyO" => s(0x18),
        "KeyP" => s(0x19),
        "BracketLeft" => s(0x1a),
        "BracketRight" => s(0x1b),
        "Enter" => s(0x1c),
        "ControlLeft" => s(0x1d),
        "KeyA" => s(0x1e),
        "KeyS" => s(0x1f),
        "KeyD" => s(0x20),
        "KeyF" => s(0x21),
        "KeyG" => s(0x22),
        "KeyH" => s(0x23),
        "KeyJ" => s(0x24),
        "KeyK" => s(0x25),
        "KeyL" => s(0x26),
        "Semicolon" => s(0x27),
        "Quote" => s(0x28),
        "Backquote" => s(0x29),
        "ShiftLeft" => s(0x2a),
        "Backslash" => s(0x2b),
        "KeyZ" => s(0x2c),
        "KeyX" => s(0x2d),
        "KeyC" => s(0x2e),
        "KeyV" => s(0x2f),
        "KeyB" => s(0x30),
        "KeyN" => s(0x31),
        "KeyM" => s(0x32),
        "Comma" => s(0x33),
        "Period" => s(0x34),
        "Slash" => s(0x35),
        "ShiftRight" => s(0x36),
        "NumpadMultiply" => s(0x37),
        "AltLeft" => s(0x38),
        "Space" => s(0x39),
        "CapsLock" => s(0x3a),
        "F1" => s(0x3b),
        "F2" => s(0x3c),
        "F3" => s(0x3d),
        "F4" => s(0x3e),
        "F5" => s(0x3f),
        "F6" => s(0x40),
        "F7" => s(0x41),
        "F8" => s(0x42),
        "F9" => s(0x43),
        "F10" => s(0x44),
        "F11" => s(0x57),
        "F12" => s(0x58),
        "NumLock" => s(0x45),
        "ScrollLock" => s(0x46),
        "Numpad7" => s(0x47),
        "Numpad8" => s(0x48),
        "Numpad9" => s(0x49),
        "NumpadSubtract" => s(0x4a),
        "Numpad4" => s(0x4b),
        "Numpad5" => s(0x4c),
        "Numpad6" => s(0x4d),
        "NumpadAdd" => s(0x4e),
        "Numpad1" => s(0x4f),
        "Numpad2" => s(0x50),
        "Numpad3" => s(0x51),
        "Numpad0" => s(0x52),
        "NumpadDecimal" => s(0x53),
        "IntlBackslash" => s(0x56),
        "IntlRo" => s(0x73),
        "IntlYen" => s(0x7d),
        "NumpadEnter" => e(0x1c),
        "ControlRight" => e(0x1d),
        "NumpadDivide" => e(0x35),
        "PrintScreen" => e(0x37),
        "AltRight" => e(0x38),
        "Home" => e(0x47),
        "ArrowUp" => e(0x48),
        "PageUp" => e(0x49),
        "ArrowLeft" => e(0x4b),
        "ArrowRight" => e(0x4d),
        "End" => e(0x4f),
        "ArrowDown" => e(0x50),
        "PageDown" => e(0x51),
        "Insert" => e(0x52),
        "Delete" => e(0x53),
        "MetaLeft" | "OSLeft" => e(0x5b),
        "MetaRight" | "OSRight" => e(0x5c),
        "ContextMenu" => e(0x5d),
        "Pause" => s(0x45),
        _ => None,
    }
}
